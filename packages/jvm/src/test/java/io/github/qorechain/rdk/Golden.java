package io.github.qorechain.rdk;

import com.google.gson.Gson;
import java.io.InputStream;
import java.io.InputStreamReader;
import java.nio.charset.StandardCharsets;
import java.util.List;
import java.util.Map;

/** Loads the {@code golden.json} cross-language fixture from test resources. */
final class Golden {
    String mnemonic;
    String nativeAddress;
    String privateKeyHex;
    Map<String, String> denom;
    Map<String, String> economics;
    MerkleSection merkle;
    Map<String, String> msgProtoHex;
    Map<String, Map<String, Object>> presetDefaults;
    AnchorSignBytesSection anchorSignBytes;
    MldsaVectorSection mldsaVector;
    WithdrawalLeafSection withdrawalLeaf;
    WithdrawalTreeSection withdrawalTree;
    DaBlobSection daBlob;
    HybridTxSection hybridTx;

    static final class MerkleSection {
        String hash;
        List<String> leavesHex;
        String root;
        List<String> proofIndex1Siblings;
        /** The SHA-256 values the generic helpers produced before 0.7.0. */
        MerkleLegacy sha256Legacy;
    }

    static final class MerkleLegacy {
        String root;
        List<String> proofIndex1Siblings;
    }

    static final class WithdrawalLeafSection {
        String rollupId;
        long withdrawalIndex;
        String recipient;
        String denom;
        long amount;
        String v1;
        String v2ChainId;
        String v2;
    }

    /** Every proof here is accepted by the chain's own VerifyWithdrawalMerkle. */
    static final class WithdrawalTreeSection {
        String chainId;
        String rollupId;
        String denom;
        List<WithdrawalEntry> withdrawals;
        WithdrawalTreeVersion v1;
        WithdrawalTreeVersion v2;
    }

    static final class WithdrawalEntry {
        String recipient;
        long amount;
    }

    static final class WithdrawalTreeVersion {
        List<String> leaves;
        String root;
        List<List<String>> proofs;
    }

    static final class DaBlobSection {
        String dataUtf8;
        String commitment;
    }

    static final class AnchorSignBytesSection {
        String layerId;
        long layerHeight;
        String stateRoot;
        String validatorSetHash;
        String expectedHex;
        String expectedHexV1;
        AnchorV2Section v2;
    }

    /** Generated by calling the chain's own x/multilayer/types.AnchorSignBytesV2. */
    static final class AnchorV2Section {
        String chainId;
        String layerId;
        long layerHeight;
        String stateRoot;
        String validatorSetHash;
        long transactionCount;
        String compressedStateProof;
        String expectedHex;
    }

    static final class MldsaVectorSection {
        String algorithm;
        String messageUtf8;
        String publicKeyHex;
        String signatureHex;
    }

    /**
     * Hybrid transactions the TypeScript SDK built for one fixed input. ML-DSA-87 signing is
     * deterministic, so every client must produce these exact bytes.
     */
    static final class HybridTxSection {
        String chainId;
        long accountNumber;
        long sequence;
        HybridFee fee;
        String memo;
        HybridMessage message;
        HybridVector v1;
        HybridVector v1WithKey;
        HybridVector v2;
        HybridVector v2WithKey;
    }

    static final class HybridFee {
        List<Map<String, String>> amount;
        String gas;
    }

    static final class HybridMessage {
        String typeUrl;
        String creator;
        String rollupId;
        String reason;
    }

    static final class HybridVector {
        String txRawHex;
        String pqcSignedMessageHex;
    }

    static Golden load() {
        try (InputStream in = Golden.class.getResourceAsStream("/golden.json")) {
            if (in == null) {
                throw new IllegalStateException("golden.json not found on classpath");
            }
            return new Gson().fromJson(new InputStreamReader(in, StandardCharsets.UTF_8), Golden.class);
        } catch (Exception e) {
            throw new RuntimeException("failed to load golden.json", e);
        }
    }
}
