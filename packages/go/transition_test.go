type transitionGolden struct {
	TransitionRoot struct {
		ChainID         string `json:"chainId"`
		RollupID        string `json:"rollupId"`
		PrevStateRoot   string `json:"prevStateRoot"`
		DataHash        string `json:"dataHash"`
		TxCount         uint64 `json:"txCount"`
		WithdrawalsRoot string `json:"withdrawalsRoot"`
		V1              string `json:"v1"`
		V2              string `json:"v2"`
		V2OtherChain    struct {
			ChainID string `json:"chainId"`
			Root    string `json:"root"`
		} `json:"v2OtherChain"`
		EmptyBatch struct {
			V1 string `json:"v1"`
			V2 string `json:"v2"`
		} `json:"emptyBatch"`
	} `json:"transitionRoot"`
}

func mustHex(t *testing.T, s string) []byte {
	t.Helper()
	b, err := hex.DecodeString(s)
	if err != nil {
		t.Fatal(err)
	}
	return b
}

// Vectors generated by calling the chain's own BatchTransitionRoot.
func TestBatchTransitionRootMatchesTheChain(t *testing.T) {
	raw, err := os.ReadFile("testdata/golden.json")
	if err != nil {
		t.Fatal(err)
	}
	var g transitionGolden
	if err := json.Unmarshal(raw, &g); err != nil {
		t.Fatal(err)
	}
	v := g.TransitionRoot
	in := TransitionInput{ChainID: v.ChainID, RollupID: v.RollupID, PrevStateRoot: mustHex(t, v.PrevStateRoot),
		DataHash: mustHex(t, v.DataHash), TxCount: v.TxCount, WithdrawalsRoot: mustHex(t, v.WithdrawalsRoot)}
	if got := hex.EncodeToString(BatchTransitionRootV1(in)); got != v.V1 {
		t.Fatalf("v1 %s, chain %s", got, v.V1)
	}
	v2, err := BatchTransitionRootV2(in)
	if err != nil || hex.EncodeToString(v2) != v.V2 {
		t.Fatalf("v2 %x (%v), chain %s", v2, err, v.V2)
	}
	other := in
	other.ChainID = v.V2OtherChain.ChainID
	if r, _ := BatchTransitionRoot(other, "v2"); hex.EncodeToString(r) != v.V2OtherChain.Root {
		t.Fatalf("v2 on %s: %x", other.ChainID, r)
	}
	empty := TransitionInput{ChainID: v.ChainID, RollupID: v.RollupID, PrevStateRoot: in.PrevStateRoot, TxCount: 1}
	if got := hex.EncodeToString(BatchTransitionRootV1(empty)); got != v.EmptyBatch.V1 {
		t.Fatalf("empty v1 %s", got)
	}
	if r, _ := BatchTransitionRootV2(empty); hex.EncodeToString(r) != v.EmptyBatch.V2 {
		t.Fatalf("empty v2 %x", r)
	}
	if _, err := BatchTransitionRootV2(TransitionInput{RollupID: "r", PrevStateRoot: in.PrevStateRoot}); err == nil {
		t.Fatal("v2 without a chain id must fail")
	}
	bad := in
	bad.WithdrawalsRoot = []byte{1, 2}
	if _, err := BatchTransitionRootV2(bad); err == nil || !strings.Contains(err.Error(), "32 bytes") {
		t.Fatalf("malformed withdrawals root: %v", err)
	}
}

func transitionServer(t *testing.T, featureStatus int, enabled bool, applied string) *RestClient {
	t.Helper()
	srv := httptest.NewServer(http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
		switch {
		case strings.Contains(r.URL.Path, "protocol_features"):
			if featureStatus != 200 {
				w.WriteHeader(featureStatus)
				return
			}
			fmt.Fprintf(w, `{"features":[{"name":"rdk-withdrawals-binding","enabled":%t}]}`, enabled)
		case strings.HasSuffix(r.URL.Path, "/applied_plan/v3.2.5"):
			fmt.Fprintf(w, `{"height":%q}`, applied)
		default:
			http.NotFound(w, r)
		}
	}))
	t.Cleanup(srv.Close)
	return NewRestClient(srv.URL, srv.Client())
}

func TestTransitionRootVersion(t *testing.T) {
	ctx := context.Background()
	for _, c := range []struct {
		status  int
		enabled bool
		want    string
	}{{200, true, "v2"}, {200, false, "v1"}, {501, false, "v1"}, {404, false, "v1"}} {
		got, err := TransitionRootVersionFor(ctx, transitionServer(t, c.status, c.enabled, "0"))
		if err != nil || got != c.want {
			t.Fatalf("status %d enabled %t: %s %v", c.status, c.enabled, got, err)
		}
	}
	if _, err := TransitionRootVersionFor(ctx, transitionServer(t, 500, false, "0")); err == nil {
		t.Fatal("a 500 must be an error, not a guess")
	}
	rest := transitionServer(t, 200, true, "8890800")
	for _, c := range []struct {
		at   int
		want string
	}{{8890800, "v2"}, {8890799, "v1"}} {
		if got, _ := TransitionRootVersionForBatch(ctx, rest, BatchView{SubmittedAt: c.at}); got != c.want {
			t.Fatalf("batch at %d: %s", c.at, got)
		}
	}
	if got, _ := TransitionRootVersionForBatch(ctx, transitionServer(t, 200, false, "0"), BatchView{SubmittedAt: 9e6}); got != "v1" {
		t.Fatal("before the upgrade applies every batch is v1")
	}
	if got, _ := TransitionRootVersionForBatch(ctx, rest, BatchView{SubmittedAt: 1, WithdrawalsBound: true}); got != "v2" {
		t.Fatal("the batch's own flag wins")
	}
}

func TestFraudProofLayout(t *testing.T) {
	p, err := FraudProof(mustHex(t, strings.Repeat("11", 32)), mustHex(t, strings.Repeat("22", 32)))
	if err != nil || hex.EncodeToString(p) != strings.Repeat("11", 32)+strings.Repeat("22", 32) {
		t.Fatalf("%x %v", p, err)
	}
	if _, err := FraudProof([]byte{1}, p[:32]); err == nil {
		t.Fatal("short previous root must fail")
	}
}
